"""
Aion 3D Asset Browser & Model Catalog Engine for Blender.
Provides automatic 3D thumbnail rendering, asset marking, catalog classification,
and inventory grid integration matching Blender's native Asset Browser.
"""

from __future__ import annotations

import os
import tempfile
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import bpy
from mathutils import Matrix, Vector

# Standard UUIDs for Blender Asset Catalogs
CATALOG_DEFINITIONS = {
    "Architecture": ("6c7d9a10-0001-4000-8000-000000000001", "Architecture", "Architecture"),
    "Props": ("6c7d9a10-0002-4000-8000-000000000002", "Props", "Props & Furniture"),
    "Vegetation": ("6c7d9a10-0003-4000-8000-000000000003", "Vegetation", "Vegetation & Trees"),
    "Rocks": ("6c7d9a10-0004-4000-8000-000000000004", "Rocks", "Rocks & Cliffs"),
    "NPCs": ("6c7d9a10-0005-4000-8000-000000000005", "NPCs", "NPCs & Monsters"),
    "Effects": ("6c7d9a10-0006-4000-8000-000000000006", "Effects", "Effects & Dynamic"),
}

_CLIENT_MODEL_CACHE: Dict[str, List[Tuple[str, str, str]]] = {}
_SCENE_MODEL_CACHE: Dict[Tuple[str, int, int, int, str, str], List[Tuple[str, str, str, str]]] = {}


def invalidate_asset_catalog_cache() -> None:
    """Clears cached scene model queries so panels refresh cleanly after imports."""
    _SCENE_MODEL_CACHE.clear()


def is_client_model_cache_ready(client_root: Path | str) -> bool:
    """Returns True when client model paths for client_root are already indexed in memory."""
    if not client_root:
        return False
    try:
        key = str(Path(client_root).resolve()).lower()
        return key in _CLIENT_MODEL_CACHE
    except Exception:
        return False


def write_asset_catalog_file(target_dir: Path | str) -> Path:
    """Writes official blender_assets.cats.txt catalog definitions into the target folder."""
    p = Path(target_dir)
    p.mkdir(parents=True, exist_ok=True)
    cats_file = p / "blender_assets.cats.txt"

    lines = [
        "# This is an Asset Catalog Definition file for Blender.",
        "# Generated by Aion Map Toolkit.",
        "",
        "VERSION 1",
        "",
    ]
    for cat_name, (cat_uuid, cat_path, simple_name) in CATALOG_DEFINITIONS.items():
        lines.append(f"{cat_uuid}:{cat_path}:{simple_name}")

    cats_file.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return cats_file


def infer_asset_category(ref_path: str, obj_name: str = "") -> str:
    """Infers high-level catalog category from CGF path or object name."""
    s = f"{ref_path} {obj_name}".lower().replace("\\", "/")
    if any(k in s for k in ("building", "structure", "house", "wall", "castle", "bridge", "pillar", "gate")):
        return "Architecture"
    if any(k in s for k in ("tree", "grass", "plant", "flower", "bush", "veg", "leaf", "flora", "crop", "pine")):
        return "Vegetation"
    if any(k in s for k in ("rock", "cliff", "stone", "boulder", "stalag", "crystal", "mountain")):
        return "Rocks"
    if any(k in s for k in ("npc", "monster", "human", "shugo", "mob", "creature", "beast", "guard")):
        return "NPCs"
    if any(k in s for k in ("particle", "effect", "fx", "obelisk", "placeable", "sprite", "water")):
        return "Effects"
    return "Props"


def catalog_scene_assets(context: bpy.types.Context, generate_previews: bool = False) -> int:
    """
    Scans the scene for all Aion models (in .TEMPLATES and active scene collections),
    marks them as Blender Assets, tags them into categories, and optionally generates 3D thumbnail previews.
    """
    cataloged_count = 0
    seen_assets = set()

    # Determine base directory to write blender_assets.cats.txt
    cats_dir = Path.home() / "Documents" / "Aion_Blender_Assets"
    if bpy.data.filepath:
        cats_dir = Path(bpy.data.filepath).parent
    else:
        settings = getattr(context.scene, "aion_settings", None)
        active_level = getattr(settings, "loaded_level_dir", "") if settings else ""
        if active_level and Path(active_level).is_dir():
            cats_dir = Path(active_level)

    try:
        write_asset_catalog_file(cats_dir)
    except Exception:
        pass

    # Find templates collection (O(1) pointer deduplication — avoids O(N^2) list membership scans)
    templates_col = bpy.data.collections.get(".TEMPLATES")
    candidate_objects = []
    seen_ptrs = set()

    if templates_col:
        for o in templates_col.objects:
            ptr = o.as_pointer()
            if o.type in ("MESH", "EMPTY") and ptr not in seen_ptrs:
                seen_ptrs.add(ptr)
                candidate_objects.append(o)
        for child_col in templates_col.children:
            for o in child_col.objects:
                ptr = o.as_pointer()
                if o.type in ("MESH", "EMPTY") and ptr not in seen_ptrs:
                    seen_ptrs.add(ptr)
                    candidate_objects.append(o)

    # Also scan unique mesh datablocks / objects in the scene
    for o in context.scene.objects:
        if o.get("aion_source_type") or o.get("aion_reference") or o.get("aion_npc_id"):
            ptr = o.as_pointer()
            if ptr not in seen_ptrs:
                seen_ptrs.add(ptr)
                candidate_objects.append(o)

    for obj in candidate_objects:
        ref = obj.get("aion_reference") or obj.get("aion_cgf_reference") or obj.name
        norm_ref = str(ref).replace("\\", "/").strip().lower()
        if norm_ref in seen_assets:
            continue
        seen_assets.add(norm_ref)

        category = infer_asset_category(norm_ref, obj.name)
        cat_info = CATALOG_DEFINITIONS.get(category, CATALOG_DEFINITIONS["Props"])
        cat_uuid, cat_path, simple_name = cat_info

        try:
            if not getattr(obj, "asset_data", None):
                obj.asset_mark()

            if getattr(obj, "asset_data", None):
                obj.asset_data.catalog_id = cat_uuid
                obj.asset_data.description = f"Aion {category}: {norm_ref}"
                obj.asset_data.author = "Aion Classic & Retail Tools"

                # Ensure category tag exists
                existing_tags = {t.name for t in obj.asset_data.tags}
                if category not in existing_tags:
                    obj.asset_data.tags.new(category)
                if simple_name not in existing_tags:
                    obj.asset_data.tags.new(simple_name)

                if generate_previews and hasattr(obj, "asset_generate_preview"):
                    obj.asset_generate_preview()

                cataloged_count += 1
        except Exception:
            pass

    return cataloged_count


def get_scene_model_items(
    context: bpy.types.Context,
    category_filter: str = "ALL",
    search_query: str = "",
) -> List[Tuple[str, str, str, bpy.types.Object]]:
    """
    Returns filtered items from the scene (cached by scene state to avoid UI redraw lag):
    [(identifier, display_name, category, obj), ...]
    """
    scene = getattr(context, "scene", None)
    if scene is None:
        return []

    templates_col = bpy.data.collections.get(".TEMPLATES")
    tpl_count = (len(templates_col.children) + len(templates_col.objects)) if templates_col else 0
    cache_key = (
        scene.name,
        len(scene.objects),
        len(bpy.data.meshes),
        tpl_count,
        str(category_filter).upper(),
        search_query.strip().lower(),
    )
    cached_entries = _SCENE_MODEL_CACHE.get(cache_key)
    if cached_entries is not None:
        resolved_cached = []
        valid = True
        for norm_ref, disp_name, category, obj_name in cached_entries:
            obj = bpy.data.objects.get(obj_name)
            if obj is None:
                valid = False
                break
            resolved_cached.append((norm_ref, disp_name, category, obj))
        if valid:
            return resolved_cached
        _SCENE_MODEL_CACHE.pop(cache_key, None)

    results = []
    seen = set()
    seen_ptrs = set()
    candidate_objects = []

    if templates_col:
        for o in templates_col.objects:
            ptr = o.as_pointer()
            if o.type in ("MESH", "EMPTY") and ptr not in seen_ptrs:
                seen_ptrs.add(ptr)
                candidate_objects.append(o)
        for child_col in templates_col.children:
            for o in child_col.objects:
                ptr = o.as_pointer()
                if o.type in ("MESH", "EMPTY") and ptr not in seen_ptrs:
                    seen_ptrs.add(ptr)
                    candidate_objects.append(o)

    for o in scene.objects:
        if o.get("aion_source_type") or o.get("aion_reference"):
            ptr = o.as_pointer()
            if ptr not in seen_ptrs:
                seen_ptrs.add(ptr)
                candidate_objects.append(o)

    query_lower = search_query.strip().lower()

    for obj in candidate_objects:
        ref = str(obj.get("aion_reference") or obj.get("aion_cgf_reference") or obj.name)
        norm_ref = ref.replace("\\", "/").strip().lower()
        if norm_ref in seen:
            continue
        seen.add(norm_ref)

        category = infer_asset_category(norm_ref, obj.name)
        if category_filter != "ALL" and category.upper() != category_filter.upper():
            continue

        if query_lower and query_lower not in norm_ref and query_lower not in obj.name.lower():
            continue

        disp_name = Path(norm_ref).stem or obj.name
        results.append((norm_ref, disp_name, category, obj))

    results.sort(key=lambda x: (x[2], x[1]))
    if len(_SCENE_MODEL_CACHE) > 32:
        _SCENE_MODEL_CACHE.clear()
    _SCENE_MODEL_CACHE[cache_key] = [
        (norm_ref, disp_name, category, obj.name)
        for norm_ref, disp_name, category, obj in results
    ]
    return results


def get_client_model_items(
    client_root: Path | str,
    category_filter: str = "ALL",
    search_query: str = "",
    limit: int = 150,
    *,
    allow_scan: bool = True,
) -> List[Tuple[str, str, str]]:
    """
    Scans and caches 3D CGF/CGA models from client mesh PAK archives.
    When allow_scan=False (used during UI redraws), only returns already cached entries
    so drawing panels never performs synchronous PAK I/O on the main thread.
    Returns [(relative_path, display_name, category), ...]
    """
    root = Path(client_root).resolve()
    key = str(root).lower()
    if key not in _CLIENT_MODEL_CACHE:
        if not allow_scan:
            return []
        from core.pak_engine import AionPakArchive

        all_models = []
        paks = list((root / "Objects").glob("*_Meshes.pak")) + list(
            (root / "Objects").glob("*/*_Meshes*.pak")
        )
        common_dir = root / "levels" / "common"
        if common_dir.is_dir():
            paks.extend(common_dir.glob("*.pak"))
        data_world = root / "Data" / "world"
        if data_world.is_dir():
            paks.extend(data_world.glob("*.pak"))

        seen = set()
        for p in paks:
            try:
                with AionPakArchive(p) as arc:
                    for entry_name in arc.entries.keys():
                        if entry_name.endswith(".cgf") or entry_name.endswith(".cga"):
                            clean = entry_name.replace("\\", "/").strip().lstrip("/")
                            if clean not in seen:
                                seen.add(clean)
                                cat = infer_asset_category(clean)
                                disp = Path(clean).stem
                                all_models.append((clean, disp, cat))
            except Exception:
                pass
        _CLIENT_MODEL_CACHE[key] = sorted(all_models, key=lambda x: (x[2], x[1]))

    cached = _CLIENT_MODEL_CACHE.get(key, [])
    cat_filt = category_filter.upper().strip()
    q_lower = search_query.lower().strip()

    filtered = []
    for rel_path, disp, cat in cached:
        if cat_filt != "ALL" and cat.upper() != cat_filt:
            continue
        if q_lower and q_lower not in rel_path.lower() and q_lower not in disp.lower():
            continue
        filtered.append((rel_path, disp, cat))
        if limit > 0 and len(filtered) >= limit:
            break

    return filtered


def spawn_asset_at_location(
    context: bpy.types.Context,
    target_obj: bpy.types.Object,
    location: Vector | Tuple[float, float, float],
    snap_terrain: bool = True,
) -> Optional[bpy.types.Object]:
    """Spawns a new instance of target_obj at the given location, optionally snapping to terrain."""
    if not target_obj:
        return None

    from editing.object_editor import snap_objects_to_terrain
    from editing.roundtrip_tracker import tag_object_instance

    # Link to category collection
    category = infer_asset_category(target_obj.get("aion_reference", ""), target_obj.name)
    target_col = (
        bpy.data.collections.get(category.upper())
        or bpy.data.collections.get("PROPS")
        or context.scene.collection
    )

    if target_obj.type == "MESH":
        new_inst = bpy.data.objects.new(f"{target_obj.name}_inst", target_obj.data)
        new_inst.location = location
        target_col.objects.link(new_inst)
    else:
        new_inst = bpy.data.objects.new(f"{target_obj.name}_inst", None)
        new_inst.instance_type = "COLLECTION"
        new_inst.instance_collection = (
            target_obj.instance_collection
            if hasattr(target_obj, "instance_collection")
            else None
        )
        new_inst.location = location
        target_col.objects.link(new_inst)

    # Tag instance for round-trip tracking
    ref = target_obj.get("aion_reference") or target_obj.name
    tag_object_instance(
        new_inst,
        source_type="brush" if category in ("Architecture", "Props", "Rocks") else "object",
        source_index=-1,
        cgf_reference=str(ref),
        matrix=new_inst.matrix_world,
    )

    if snap_terrain:
        snap_objects_to_terrain([new_inst])

    # Select the new instance
    for o in context.selected_objects:
        o.select_set(False)
    new_inst.select_set(True)
    context.view_layer.objects.active = new_inst

    return new_inst


def import_and_spawn_client_model(
    context: bpy.types.Context,
    client_root: Path | str,
    cgf_relative_path: str,
    location: Vector | Tuple[float, float, float] | None = None,
    snap_terrain: bool = True,
) -> Optional[bpy.types.Object]:
    """
    Dynamically loads a CGF model from the client archives, creates/reuses a template
    object in .TEMPLATES, marks it as an asset with 3D preview, and spawns an instance
    at the specified location (or 3D cursor) with optional terrain snap.
    """
    from core.client_provider import AionClientProvider
    from importers.cgf_importer import load

    if location is None:
        location = context.scene.cursor.location

    provider = AionClientProvider(client_root)
    # Ensure relevant PAKs are indexed
    paks = list((provider.root / "Objects").glob("*_Meshes.pak")) + list(
        (provider.root / "Objects").glob("*/*_Meshes*.pak")
    )
    for p in paks:
        provider.catalog.index_pak(p)

    data = provider.catalog.extract_file(cgf_relative_path)
    if not data:
        data = provider.catalog.extract_file(Path(cgf_relative_path).name)
    if not data:
        data = provider.resolve_cgf_bytes(cgf_relative_path)

    if not data:
        print(f"[AssetCatalog] Failed to resolve model bytes for {cgf_relative_path}")
        return None

    # Save to temp file and load via cgf_importer
    temp_dir = Path(tempfile.gettempdir()) / "aion_asset_import"
    temp_dir.mkdir(parents=True, exist_ok=True)
    clean_stem = Path(cgf_relative_path).stem
    temp_file = temp_dir / f"{clean_stem}.cgf"
    temp_file.write_bytes(data)

    try:
        # Load object
        res = load(context, temp_file, import_mode="VISUAL")
        imported_objs = [o for o in context.selected_objects if o.type == "MESH"]
        if not imported_objs and context.active_object:
            imported_objs = [context.active_object]

        if not imported_objs:
            return None

        primary_obj = imported_objs[0]
        primary_obj["aion_reference"] = cgf_relative_path
        primary_obj["aion_source_type"] = (
            "brush"
            if infer_asset_category(cgf_relative_path) in ("Architecture", "Props", "Rocks")
            else "object"
        )

        # Organize into .TEMPLATES collection
        templates_col = bpy.data.collections.get(".TEMPLATES")
        if not templates_col:
            templates_col = bpy.data.collections.new(".TEMPLATES")
            context.scene.collection.children.link(templates_col)

        cat = infer_asset_category(cgf_relative_path, primary_obj.name)
        cat_col = bpy.data.collections.get(f".TEMPLATES_{cat.upper()}")
        if not cat_col:
            cat_col = bpy.data.collections.new(f".TEMPLATES_{cat.upper()}")
            templates_col.children.link(cat_col)

        # Unlink from scene root and link to template col
        for col in list(primary_obj.users_collection):
            col.objects.unlink(primary_obj)
        cat_col.objects.link(primary_obj)

        # Mark as asset and generate 3D preview
        try:
            if not getattr(primary_obj, "asset_data", None):
                primary_obj.asset_mark()
            if getattr(primary_obj, "asset_data", None):
                cat_info = CATALOG_DEFINITIONS.get(cat, CATALOG_DEFINITIONS["Props"])
                primary_obj.asset_data.catalog_id = cat_info[0]
                primary_obj.asset_data.description = f"Aion {cat}: {cgf_relative_path}"
                primary_obj.asset_data.author = "Aion Classic & Retail Tools"
                if hasattr(primary_obj, "asset_generate_preview"):
                    primary_obj.asset_generate_preview()
        except Exception:
            pass

        # Spawn instance at location
        inst = spawn_asset_at_location(
            context, primary_obj, location, snap_terrain=snap_terrain
        )
        return inst
    finally:
        temp_file.unlink(missing_ok=True)
