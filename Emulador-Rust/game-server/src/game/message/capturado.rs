/// Offset do nome dentro do [`PUT_USER`], em UTF-16LE.
///
/// O campo e de **tamanho variavel**, terminado em `00 00` -- nao ha preenchimento entre o fim do
/// nome e o `ff ff` seguinte. Por isso trocar o nome muda o tamanho do pacote, e a funcao abaixo
/// devolve um `Vec` de comprimento diferente do molde. Duas coisas confirmam o formato: os dois
/// `S_PUT_USER` da captura tem tamanhos diferentes (481 e 735 bytes), e o `PutUser` do POC tambem
/// escreve o nome sem padding, com o bloco seguinte comecando em `00 00`.
pub const PUT_USER_NOME: usize = 55;

/// Escreve `nome` por cima do nome capturado no [`PUT_USER`].
///
/// Sem isso todo personagem entra no mundo chamado `Kimmie`, que e quem estava logado na captura --
/// a lista mostra o nome certo, porque o registro da lista tem o campo escrito por cima, e o mundo
/// mostra o capturado.
pub fn com_nome_de_personagem(payload: &[u8], offset: usize, nome: &str) -> Vec<u8> {
    // O fim do nome capturado e o primeiro par 00 00 alinhado a partir do offset.
    let mut fim = offset;
    while fim + 1 < payload.len() && !(payload[fim] == 0 && payload[fim + 1] == 0) {
        fim += 2;
    }

    let mut saida = Vec::with_capacity(payload.len() + 32);
    saida.extend_from_slice(&payload[..offset]);
    for c in nome.encode_utf16() {
        saida.extend_from_slice(&c.to_le_bytes());
    }
    saida.extend_from_slice(&payload[fim..]);
    saida
}

/// Onde a aparencia mora dentro do [`PUT_USER`].
///
/// O `PUT_USER` tem layout proprio, diferente do registro da lista -- mas o trecho de cores, rosto
/// e altura e o mesmo bloco, deslocado de 243: as quatro cores da Kimmie aparecem em 315/319/323/
/// 327 (contra 72/76/80/84 no registro), os 52 bytes de rosto em 331 (contra 88) e a altura em 383
/// da 0.65, que e o valor documentado dela.
///
/// Identidade fica no cabecalho: a redundancia `100000 + raca * 2 + genero` em 16, e a classe como
/// **um byte** em 42. A redundancia seleciona o mesh do corpo e por isso fica sem escrever -- ver
/// [`com_aparencia_de_personagem`]. Nas 12 amostras da captura a classe varia (7, 19, 4) e a redundancia nao,
/// porque todos os jogadores eram da mesma raca e genero.
///
/// Raca e genero ficam entre os offsets 36, 41, 43 e 44: sao os unicos que **nao variam** entre os
/// 14 jogadores da captura, e todos eles eram da mesma raca e do mesmo genero. Uma captura so nao
/// separa qual e qual, entao os dois saem por variavel de ambiente:
///
/// ```text
/// AION_PUT_USER_RACA=41     AION_PUT_USER_GENERO=43
/// ```
///
/// Aceitam lista separada por virgula. Sem elas, nada e escrito -- que era o comportamento antes
/// de existirem.
pub mod put_user {
    /// `100000 + raca * 2 + genero`, u32.
    pub const REDUNDANCIA: usize = 16;
    /// Classe, um byte.
    pub const CLASSE: usize = 42;
    /// Inicio do bloco de cores + rosto + altura, 72 bytes.
    pub const CORES: usize = 315;
    /// Tamanho desse bloco: da cor da pele ate o fim da altura.
    pub const CORES_LEN: usize = 72;
}

/// Escreve a aparencia escolhida pelo jogador por cima do [`PUT_USER`] capturado.
///
/// Onde a posicao do personagem aparece dentro do `S_PUT_USER`.
///
/// Duas vezes, com os mesmos tres floats. Achadas varrendo o blob atras de triplas que caem na
/// faixa de coordenada de mundo: so estas duas aparecem, e as duas trazem
/// `(1295.82, 1416.31, 208.12)` -- onde a personagem da captura estava, em Pandaemonium.
///
/// Sem escrever por cima, o cliente carrega o mapa no ponto que o `S_WORLD` mandou e poe o
/// **corpo** no ponto da captura. Para um personagem elyos em Sanctum a diferenca de altura e de
/// 360 metros, e o resultado e o personagem debaixo do cenario, olhando a cidade de baixo. Parece
/// falta de geodata, e nao e.
pub const PUT_USER_POSICAO: [usize; 2] = [0, 418];

/// Escreve a posicao do personagem no `S_PUT_USER`.
///
/// Tem que rodar **antes** de [`com_nome_de_personagem`], pelo mesmo motivo da aparencia: o nome
/// muda o tamanho do pacote e desloca o offset 418.
pub fn com_posicao_de_personagem(payload: &[u8], x: f32, y: f32, z: f32) -> Vec<u8> {
    let mut saida = payload.to_vec();
    for off in PUT_USER_POSICAO {
        if off + 12 <= saida.len() {
            saida[off..off + 4].copy_from_slice(&x.to_le_bytes());
            saida[off + 4..off + 8].copy_from_slice(&y.to_le_bytes());
            saida[off + 8..off + 12].copy_from_slice(&z.to_le_bytes());
        }
    }
    saida
}

/// `bloco` sao os 140 bytes que o cliente mandou ao criar o personagem -- o mesmo trecho `4..144`
/// do registro da lista. Sem isso o personagem entra no mundo com a cara, a raca e a classe da
/// `Kimmie`, que e de quem o pacote foi capturado.
///
/// Tem que rodar **antes** de [`com_nome_de_personagem`]: o nome fica no offset 55 e trocar ele
/// muda o tamanho do pacote, deslocando tudo o que vem depois -- inclusive o bloco de cores.
pub fn com_aparencia_de_personagem(payload: &[u8], bloco: &[u8]) -> Vec<u8> {
    use super::molde::campo;

    let mut saida = payload.to_vec();
    if bloco.len() != campo::APARENCIA_LEN {
        return saida;
    }

    // Offsets dentro do bloco: ele comeca no campo de nome do registro.
    let u32_em = |off: usize| {
        u32::from_le_bytes(bloco[off - campo::NOME..][..4].try_into().unwrap())
    };
    let genero = u32_em(campo::GENERO);
    let raca = u32_em(campo::RACA);
    let classe = u32_em(campo::CLASSE);

    saida[put_user::CLASSE] = classe as u8;

    // A redundancia NAO e escrita, e a bisseccao mostrou por que. Com ela ligada e um personagem
    // elyos, o modelo no mundo entra sem cabeca; desligando so ela, com todo o resto igual, a
    // cabeca volta. Ela seleciona o mesh do corpo, e o `PUT_USER` capturado e de uma personagem
    // asmodiana: trocar so este campo pede um corpo elyos e o resto do pacote nao acompanha.
    //
    // Enquanto o pacote for um molde remendado, a raca no mundo e a da captura. Sai daqui quando o
    // `S_PUT_USER` for construido campo a campo -- e ai este campo volta, junto com os outros.
    //
    // `AION_PUT_USER_COM_RED=1` religa, para quando alguem for atras do resto do mesh.
    if std::env::var("AION_PUT_USER_COM_RED").is_ok() {
        println!("INFO: AION_PUT_USER_COM_RED -- escrevendo a redundancia (modelo pode quebrar)");
        saida[put_user::REDUNDANCIA..put_user::REDUNDANCIA + 4]
            .copy_from_slice(&(100_000 + raca * 2 + genero).to_le_bytes());
    }

    for off in offsets_de("AION_PUT_USER_RACA") {
        if off < saida.len() {
            saida[off] = raca as u8;
        }
    }
    for off in offsets_de("AION_PUT_USER_GENERO") {
        if off < saida.len() {
            saida[off] = genero as u8;
        }
    }

    // Cores, rosto e altura: um pedaco continuo, identico ao do registro.
    //
    // O tamanho e ajustavel para bisseccao, porque escrever os 72 bytes deixou o personagem sem
    // cabeca no mundo -- antes disso ele aparecia inteiro, com a cara da captura. Os cortes uteis:
    //
    // ```text
    // AION_PUT_USER_CORES_LEN=0    nao escreve nada  (controle: a cabeca deve voltar)
    //                        =16   so as quatro cores
    //                        =68   cores e rosto, sem a altura
    //                        =72   tudo (padrao)
    // ```
    let quanto = std::env::var("AION_PUT_USER_CORES_LEN")
        .ok()
        .and_then(|v| v.trim().parse::<usize>().ok())
        .map(|v| v.min(put_user::CORES_LEN))
        .unwrap_or(put_user::CORES_LEN);
    if quanto != put_user::CORES_LEN {
        println!("INFO: AION_PUT_USER_CORES_LEN={quanto} (de {})", put_user::CORES_LEN);
    }
    let de = campo::COR_PELE - campo::NOME;
    saida[put_user::CORES..put_user::CORES + quanto]
        .copy_from_slice(&bloco[de..de + quanto]);

    saida
}

