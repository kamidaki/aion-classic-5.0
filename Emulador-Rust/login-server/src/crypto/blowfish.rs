#[derive(Clone)]
pub struct BlowfishCipher {
    p_array: [u32; 18],
    s_boxes: [[u32; 256]; 4],
}

impl BlowfishCipher {
    pub fn new(key: &[u8]) -> Self {
        let mut cipher = Self {
            p_array: [0u32; 18],
            s_boxes: [[0u32; 256]; 4],
        };
        cipher.update_key(key);
        cipher
    }

    pub fn update_key(&mut self, key: &[u8]) {
        self.s_boxes[0].copy_from_slice(&SBOX_INIT_0);
        self.s_boxes[1].copy_from_slice(&SBOX_INIT_1);
        self.s_boxes[2].copy_from_slice(&SBOX_INIT_2);
        self.s_boxes[3].copy_from_slice(&SBOX_INIT_3);

        let mut key_idx = 0;
        for i in 0..18 {
            let mut data = 0u32;
            for _ in 0..4 {
                data = (data << 8) | (key[key_idx] as u32 & 0xFF);
                key_idx += 1;
                if key_idx >= key.len() {
                    key_idx = 0;
                }
            }
            self.p_array[i] = PARRAY_INIT[i] ^ data;
        }

        let mut block = [0u8; 8];
        for i in (0..18).step_by(2) {
            self.cipher_block(&mut block);
            self.p_array[i] = u32::from_le_bytes(block[0..4].try_into().unwrap());
            self.p_array[i + 1] = u32::from_le_bytes(block[4..8].try_into().unwrap());
        }

        for sbox_idx in 0..4 {
            for j in (0..256).step_by(2) {
                self.cipher_block(&mut block);
                self.s_boxes[sbox_idx][j] = u32::from_le_bytes(block[0..4].try_into().unwrap());
                self.s_boxes[sbox_idx][j + 1] = u32::from_le_bytes(block[4..8].try_into().unwrap());
            }
        }
    }

    #[inline(always)]
    fn f(&self, mut x: u32) -> u32 {
        let d = (x & 0xFF) as usize;
        x >>= 8;
        let c = (x & 0xFF) as usize;
        x >>= 8;
        let b = (x & 0xFF) as usize;
        x >>= 8;
        let a = (x & 0xFF) as usize;

        let mut y = self.s_boxes[0][a].wrapping_add(self.s_boxes[1][b]);
        y ^= self.s_boxes[2][c];
        y = y.wrapping_add(self.s_boxes[3][d]);
        y
    }

    #[inline(always)]
    fn cipher_block(&self, block: &mut [u8]) {
        let mut xl = u32::from_le_bytes(block[0..4].try_into().unwrap());
        let mut xr = u32::from_le_bytes(block[4..8].try_into().unwrap());

        for i in 0..16 {
            xl ^= self.p_array[i];
            xr = self.f(xl) ^ xr;
            std::mem::swap(&mut xl, &mut xr);
        }

        std::mem::swap(&mut xl, &mut xr);
        xr ^= self.p_array[16];
        xl ^= self.p_array[17];

        block[0..4].copy_from_slice(&xl.to_le_bytes());
        block[4..8].copy_from_slice(&xr.to_le_bytes());
    }

    #[inline(always)]
    fn decipher_block(&self, block: &mut [u8]) {
        let mut lb = u32::from_le_bytes(block[0..4].try_into().unwrap());
        let mut rb = u32::from_le_bytes(block[4..8].try_into().unwrap());

        for i in (2..=17).rev() {
            lb ^= self.p_array[i];
            rb = self.f(lb) ^ rb;
            std::mem::swap(&mut lb, &mut rb);
        }

        std::mem::swap(&mut lb, &mut rb);
        rb ^= self.p_array[1];
        lb ^= self.p_array[0];

        block[0..4].copy_from_slice(&lb.to_le_bytes());
        block[4..8].copy_from_slice(&rb.to_le_bytes());
    }

    pub fn cipher(&self, data: &mut [u8]) {
        let blocks = data.len() / 8;
        for k in 0..blocks {
            let offset = k * 8;
            self.cipher_block(&mut data[offset..offset + 8]);
        }
    }

    pub fn decipher(&self, data: &mut [u8]) {
        let blocks = data.len() / 8;
        for k in 0..blocks {
            let offset = k * 8;
            self.decipher_block(&mut data[offset..offset + 8]);
        }
    }
}
